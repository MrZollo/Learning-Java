public class Vehicle {
    private String color;
    private int speed, size;

    public String getColor(){
        return color;
    }

    public void setColor(String i){
        color = i;
    }

    public int getSize(){
        return size;
    }

    public void setSize(int i){
        size = i;
    }

    public int getSpeed(){
        return speed;
    }

    public void setSpeed(int i){
        speed = i;
    }
}
